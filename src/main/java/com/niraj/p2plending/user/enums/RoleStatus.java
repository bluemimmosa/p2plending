package com.niraj.p2plending.user.enums;

/**
 * Indicates whether a role is available
 * for assignment.
 *
 * @author Niraj Khadka
 * @since 1.0.0
 */
public enum RoleStatus {

    /**
     * Role can be assigned to users.
     */
    ACTIVE,

    /**
     * Role is disabled and cannot be assigned.
     */
    INACTIVE

}